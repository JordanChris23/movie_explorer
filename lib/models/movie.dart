class Movie {
  final int id;
  final String title;
  final String genre;
  final int year;
  final double rating;
  final String imageUrl;
  final String description;

  Movie({
    required this.id,
    required this.title,
    required this.genre,
    required this.year,
    required this.rating,
    required this.imageUrl,
    required this.description,
  });
}